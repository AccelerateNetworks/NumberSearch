            }

            string[] fieldsArray = Fields.Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries);

            if (Fields is "line_type_intelligence")
            {
                return TypedResults.Ok(new NumberLookupResponse(
