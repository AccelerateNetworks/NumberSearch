        /// <summary>
        /// Gets the phone numbers related to the authenticated user's account, based on the destinations registered to their domain in FusionPBX.
        /// </summary>
        /// <param name="token">An API key generated by your user account in FusionPBX.</param>
        /// <param name="mvcConfiguration">The configuration for the application.</param>
        /// <returns>An array of ClientNumbers.</returns>
        public static async Task<Results<Ok<ClientNumber[]>, BadRequest<string>>> ClientNumbersAsync([Required] string token, [FromServices] MvcConfiguration mvcConfiguration)
        {
            var fusionPBXUser = await AuthenticateFusionPBXApiKeyAsync(token, mvcConfiguration);

            if (fusionPBXUser.user_uuid == Guid.Empty)
            {
                return TypedResults.BadRequest("Token is invalid. Please supply the correct token in your request or contact support@acceleratenetworks.com for help.");
            }

            var destinations = await DestinationDetails.GetByDomainIdAsync(fusionPBXUser.domain_uuid ?? Guid.Empty, mvcConfiguration.FusionPBXConnectionString.AsMemory());

            var numbers = destinations.AsValueEnumerable()
                .Where(x => !string.IsNullOrWhiteSpace(x.destination_number))
                .Select(x => new ClientNumber(x.destination_number, x.destination_description, x.destination_enabled, x.destination_type))
                .ToArray();

            return TypedResults.Ok(numbers);
        }

        /// <summary>
        /// Performs a bulk lookup for dialed phone numbers that are related to the authenticated user's account.
        /// Only numbers registered as destinations in the user's FusionPBX domain are looked up, any other numbers in the query are ignored.
        /// Numbers match even when supplied with a country code prefix, so +12065551234 and 12065551234 both match a destination stored as 2065551234.
        /// </summary>
        /// <param name="token">An API key generated by your user account in FusionPBX.</param>
        /// <param name="dialedNumber">A comma-separated list of dialed phone numbers related to your user account.</param>
        /// <param name="mvcConfiguration">The configuration for the application.</param>
        /// <returns></returns>
        public static async Task<Results<Ok<BulkLookupResult[]>, BadRequest<string>>> ClientNumberSearchAsync([Required] string token, [Required] string dialedNumber, [FromServices] MvcConfiguration mvcConfiguration)
        {
            var fusionPBXUser = await AuthenticateFusionPBXApiKeyAsync(token, mvcConfiguration);

            if (fusionPBXUser.user_uuid == Guid.Empty)
            {
                return TypedResults.BadRequest("Token is invalid. Please supply the correct token in your request or contact support@acceleratenetworks.com for help.");
            }

            var parsedNumbers = dialedNumber.ExtractDialedNumbers().ToArray();

            if (parsedNumbers.Length == 0)
            {
                return TypedResults.BadRequest("No dialed phone numbers found. Please try a different query.");
            }

            // Restrict the lookup to phone numbers that are destinations in the authenticated user's domain.
            var relatedNumbers = new ConcurrentBag<string>();
            await Parallel.ForEachAsync(parsedNumbers, async (number, token) =>
            {
                var destination = await DestinationDetails.GetByDialedNumberAndDomainAsync(number.AsMemory(), fusionPBXUser.domain_uuid ?? Guid.Empty, mvcConfiguration.FusionPBXConnectionString.AsMemory());
                if (destination.destination_uuid != Guid.Empty)
                {
                    relatedNumbers.Add(number);
                }
            });

            if (relatedNumbers.IsEmpty)
            {
                return TypedResults.BadRequest("No dialed phone numbers related to your user account found. Please try a different query.");
            }

            var results = new ConcurrentBag<PortedPhoneNumber>();
            await Parallel.ForEachAsync(relatedNumbers, async (number, token) =>
            {
                var lookup = new LookupController(mvcConfiguration);
                var result = await lookup.VerifyPortabilityAsync(number);
                results.Add(result);
            });

            var lookups = new List<BulkLookupResult>(results.Count);
            foreach (var number in results)
            {
                lookups.Add(new BulkLookupResult(number.PortedDialedNumber, number.City, number.State, number.DateIngested, number.Wireless, number.Portable, number.LrnLookup.LastPorted, number.LrnLookup.SPID, number.LrnLookup.LATA, number.LrnLookup.LEC, number.LrnLookup.LECType, number.LrnLookup.LIDBName, number.LrnLookup.LRN, number.LrnLookup.OCN, number.Carrier.Name, number.Carrier.LogoLink, number.Carrier.Color, number.Carrier.Type));
            }

            return TypedResults.Ok(lookups.ToArray());
        }

        /// <summary>
